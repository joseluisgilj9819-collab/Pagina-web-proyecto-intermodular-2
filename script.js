let currentLanguage = localStorage.getItem("mazcufit-language") || "es";

const getTranslation = (key) => translations[currentLanguage][key] || translations.es[key] || key;

const applyTranslations = (language) => {
  currentLanguage = translations[language] ? language : "es";
  localStorage.setItem("mazcufit-language", currentLanguage);
  document.documentElement.lang = currentLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    element.textContent = getTranslation(key);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    element.placeholder = getTranslation(key);
  });

  const languageSelect = document.querySelector("#languageSelect");
  if (languageSelect) {
    languageSelect.value = currentLanguage;
  }
};

const setupNavigation = () => {
  const toggle = document.querySelector(".nav-toggle");
  const panel = document.querySelector(".nav-panel");

  if (!toggle || !panel) {
    return;
  }

  toggle.addEventListener("click", () => {
    const isOpen = panel.classList.toggle("is-open");
    toggle.classList.toggle("is-open", isOpen);
    toggle.setAttribute("aria-expanded", String(isOpen));
  });

  document.querySelectorAll(".nav-panel a").forEach((link) => {
    link.addEventListener("click", () => {
      panel.classList.remove("is-open");
      toggle.classList.remove("is-open");
      toggle.setAttribute("aria-expanded", "false");
    });
  });

  const currentPage = window.location.pathname.split("/").pop() || "index.html";
  document.querySelectorAll("[data-nav]").forEach((link) => {
    if (link.dataset.nav === currentPage) {
      link.classList.add("is-active");
      link.setAttribute("aria-current", "page");
    }
  });
};

const setupForm = () => {
  const form = document.querySelector("#admissionForm");
  const status = document.querySelector("#formStatus");

  if (!form || !status) {
    return;
  }

  const showFieldError = (field, message) => {
    const error = document.querySelector(`[data-error-for="${field.id}"]`);
    field.classList.toggle("is-invalid", Boolean(message));
    if (error) {
      error.textContent = message;
    }
  };

  form.addEventListener("submit", (event) => {
    event.preventDefault();
    status.textContent = "";
    status.classList.remove("is-success");
    let isValid = true;

    Array.from(form.elements).forEach((field) => {
      if (!(field instanceof HTMLInputElement)) {
        return;
      }

      let message = "";
      if (field.validity.valueMissing) {
        message = getTranslation("formRequired");
      } else if (field.type === "email" && field.validity.typeMismatch) {
        message = getTranslation("formEmailError");
      } else if (field.name === "phone" && field.validity.patternMismatch) {
        message = getTranslation("formPhoneError");
      } else if (!field.checkValidity()) {
        message = getTranslation("formRequired");
      }

      showFieldError(field, message);
      isValid = isValid && !message;
    });

    if (!isValid) {
      return;
    }

    status.textContent = getTranslation("formSuccess");
    status.classList.add("is-success");
    form.reset();
  });
};

const setupTabs = () => {
  const buttons = document.querySelectorAll("[data-tab]");
  const panels = document.querySelectorAll("[data-panel]");

  if (!buttons.length || !panels.length) {
    return;
  }

  buttons.forEach((button) => {
    button.addEventListener("click", () => {
      const target = button.dataset.tab;

      buttons.forEach((item) => {
        const isSelected = item === button;
        item.classList.toggle("is-active", isSelected);
        item.setAttribute("aria-selected", String(isSelected));
      });

      panels.forEach((panel) => {
        const isActive = panel.dataset.panel === target;
        panel.classList.toggle("is-active", isActive);
        panel.hidden = !isActive;
      });
    });
  });
};

const setupCart = () => {
  const feedback = document.querySelector("#cartFeedback");

  if (!feedback) {
    return;
  }

  document.querySelectorAll("[data-cart-item]").forEach((button) => {
    button.addEventListener("click", () => {
      feedback.textContent = getTranslation("cartAdded").replace("{item}", button.dataset.cartItem);
      feedback.classList.add("is-success");
    });
  });
};

const setupLanguageSwitcher = () => {
  const languageSelect = document.querySelector("#languageSelect");

  if (!languageSelect) {
    return;
  }

  languageSelect.addEventListener("change", (event) => {
    applyTranslations(event.target.value);
  });
};

setupNavigation();
setupForm();
setupTabs();
setupCart();
setupLanguageSwitcher();
applyTranslations(currentLanguage);
